"""Create the copy/paste MQL5 delivery from its authoritative modular sources.

This only expands quoted, project-local includes. It never changes a strategy
function, an input, or a standard-library include. Native compilation remains
an independent MetaEditor check.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
MAIN_NAME = "RemoraScalper_MatrizObjetiva.mq5"
OUTPUT_NAME = "RemoraScalper_1996_Completo.mq5"
LOCAL_INCLUDE = re.compile(r'^\s*#include\s+"([^"\r\n]+)"\s*(?://[^\r\n]*)?(?:\r?\n)?$')


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def expand_sources(root: Path = ROOT) -> tuple[str, tuple[tuple[str, str], ...]]:
    """Read complete native files and expand each local include exactly once.

    Return the full expanded text plus the source path/hash inventory, in
    traversal order. Paths escaping the project, cycles, duplicate project
    includes and missing dependencies fail instead of producing a partial EA.
    """
    root = root.resolve()
    seen: set[Path] = set()
    inventory: list[tuple[str, str]] = []

    def expand(path: Path) -> str:
        resolved = path.resolve()
        try:
            relative = resolved.relative_to(root).as_posix()
        except ValueError as error:
            raise ValueError("Project include escapes the delivery root") from error
        if resolved in seen:
            raise ValueError("Repeated or cyclic project include: " + relative)
        seen.add(resolved)
        data = resolved.read_bytes()
        inventory.append((relative, sha256(data)))
        source = data.decode("utf-8")
        result: list[str] = []
        for line in source.splitlines(keepends=True):
            match = LOCAL_INCLUDE.fullmatch(line)
            if not match:
                result.append(line)
                continue
            included = resolved.parent / match.group(1).replace("\\", "/")
            # Include markers are comments only. The module bytes between them
            # are preserved, including every declaration and financial seam.
            body = expand(included)
            name = included.resolve().relative_to(root).as_posix()
            result.append("// BEGIN EXACT PROJECT INCLUDE: " + name + "\n")
            result.append(body)
            if body and not body.endswith("\n"):
                result.append("\n")
            result.append("// END EXACT PROJECT INCLUDE: " + name + "\n")
        return "".join(result)

    return expand(root / MAIN_NAME), tuple(inventory)


def render(root: Path = ROOT) -> str:
    body, inventory = expand_sources(root)
    lines = [
        "// GENERATED DELIVERY 1.996: exact expansion; do not edit this file directly.",
        "// Sources of truth: " + MAIN_NAME + " and its project-local includes.",
        "// Rebuild: python3 tools/build_consolidated.py",
        "// COMPILACAO_NATIVA_NAO_VERIFICADA; portable equivalence is not a MetaEditor build.",
    ]
    for name, digest in inventory:
        lines.append("// SOURCE_SHA256 " + name + " " + digest)
    lines.append("// GENERATED_BODY_BEGIN")
    return "\n".join(lines) + "\n" + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the delivered file without changing it")
    args = parser.parse_args()
    expected = render().encode("utf-8")
    output = ROOT / OUTPUT_NAME
    if args.check:
        if not output.exists() or output.read_bytes() != expected:
            parser.exit(1, "Consolidated delivery is absent or stale; run the builder.\n")
    elif not output.exists() or output.read_bytes() != expected:
        output.write_bytes(expected)
    print(OUTPUT_NAME + " SHA256=" + sha256(expected) + " bytes=" + str(len(expected)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
